<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;

class PreventBackHistory
{
    /**
     * Handle an incoming request.
     *
     * @return mixed
     */
    public function handle(Request $request, Closure $next)
    {
        $response = $next($request);

        // File downloads (receipts, agreements, exports, reports) must keep the
        // headers they were sent with. Forcing `no-store` onto an attachment
        // makes mobile browsers discard the file instead of saving it, which is
        // why receipts download on desktop but silently fail on phones.
        if ($response->headers->has('Content-Disposition')) {
            return $response;
        }

        $response->headers->set('Cache-Control', 'no-cache, no-store, max-age=0, must-revalidate');
        $response->headers->set('Pragma', 'no-cache');
        $response->headers->set('Expires', 'Sun, 02 Jan 1990 00:00:00 GMT');

        return $response;
    }
}
